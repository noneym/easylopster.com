/**
 * The uploader that runs on the OpenClaw machine (`curl … | bash -s -- TOKEN`) and its two thin
 * launchers. The real work is a Node script, because OpenClaw itself needs Node 22+, so Node is
 * always there; bash/PowerShell only download it and pass the token through.
 * The scripts are served by /import.mjs, /import.sh and /import.ps1 with the origin baked in.
 */

/** Public origin of this deployment (APP_URL, else the forwarded host of the request). */
export function appOrigin(req: Request): string {
  const env = process.env.APP_URL?.trim().replace(/\/+$/, "");
  if (env && !/localhost|127\.0\.0\.1/.test(env)) return env;
  const u = new URL(req.url);
  const host = req.headers.get("x-forwarded-host") ?? req.headers.get("host") ?? u.host;
  const proto = req.headers.get("x-forwarded-proto") ?? u.protocol.replace(":", "");
  return `${proto}://${host}`;
}

export function importMjs(origin: string): string {
  return `#!/usr/bin/env node
// easylopster — OpenClaw importer. Generated by ${origin}
// Usage: node import.mjs TOKEN [--workspace DIR] [--state-dir DIR]   (or EASYLOPSTER_IMPORT_TOKEN=TOKEN)
// Reads the OpenClaw workspace (persona, memory, skills…) and openclaw.json (bot token, model, API keys)
// and uploads them to your easylopster account. Nothing else leaves this machine.
import fs from "node:fs";
import path from "node:path";
import os from "node:os";

const API = ${JSON.stringify(origin)};
const argv = process.argv.slice(2);
let token = process.env.EASYLOPSTER_IMPORT_TOKEN || "";
let wsArg = process.env.OPENCLAW_WORKSPACE || "";
let stateArg = process.env.OPENCLAW_STATE_DIR || "";
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === "--workspace" || argv[i] === "-w") wsArg = argv[++i] || "";
  else if (argv[i] === "--state-dir") stateArg = argv[++i] || "";
  else if (!argv[i].startsWith("-")) token = argv[i];
}
const SKIP_DIRS = /^(\\.git|\\.trash[^/]*|\\.openclaw|\\.clawhub|node_modules|\\.venv|venv|__pycache__|\\.cache|dist|build)(\\/|$)/;
const MAX_FILES = 5000;
const c = { dim: "\\x1b[2m", red: "\\x1b[31m", green: "\\x1b[32m", bold: "\\x1b[1m", reset: "\\x1b[0m" };
const log = (s) => process.stdout.write(s + "\\n");
const fail = (s) => { process.stdout.write(c.red + "error: " + s + c.reset + "\\n"); process.exit(1); };
if (!token) fail("missing token. Usage: ... | bash -s -- TOKEN  (get a fresh command from the Import page)");

const home = os.homedir();
const expand = (p) => (typeof p === "string" ? p.replace(/^~(?=$|[\\/])/, home) : "");
const stateDir = () => stateArg || path.join(home, ".openclaw");

// openclaw.json is JSON5 (comments, trailing commas, unquoted keys, single quotes): a small
// recursive-descent parser covers what config files use; plain JSON is tried first.
function parseLoose(raw) {
  try { return JSON.parse(raw); } catch {}
  let i = 0;
  const n = raw.length;
  const ws = () => {
    for (;;) {
      while (i < n && /[\\s\\uFEFF]/.test(raw[i])) i++;
      if (raw.startsWith("//", i)) { while (i < n && raw[i] !== "\\n") i++; continue; }
      if (raw.startsWith("/*", i)) { const e = raw.indexOf("*/", i + 2); i = e < 0 ? n : e + 2; continue; }
      break;
    }
  };
  const str = () => {
    const q = raw[i++];
    let out = "";
    while (i < n && raw[i] !== q) {
      if (raw[i] === "\\\\") {
        const c = raw[++i];
        const map = { n: "\\n", t: "\\t", r: "\\r", b: "\\b", f: "\\f", v: "\\v", 0: "\\0", "\\n": "" };
        if (c === "u") { out += String.fromCharCode(parseInt(raw.slice(i + 1, i + 5), 16)); i += 5; continue; }
        if (c === "x") { out += String.fromCharCode(parseInt(raw.slice(i + 1, i + 3), 16)); i += 3; continue; }
        out += c in map ? map[c] : c;
        i++;
      } else out += raw[i++];
    }
    i++;
    return out;
  };
  const ident = () => { const m = /^[A-Za-z_$][\\w$]*/.exec(raw.slice(i)); if (!m) throw new Error("bad key at " + i); i += m[0].length; return m[0]; };
  const value = () => {
    ws();
    const c = raw[i];
    if (c === "{") {
      i++; const o = {};
      for (;;) {
        ws();
        if (raw[i] === "}") { i++; return o; }
        const k = raw[i] === '"' || raw[i] === "'" ? str() : ident();
        ws(); if (raw[i] !== ":") throw new Error("expected : at " + i); i++;
        o[k] = value(); ws();
        if (raw[i] === ",") { i++; continue; }
        if (raw[i] === "}") { i++; return o; }
        throw new Error("expected , or } at " + i);
      }
    }
    if (c === "[") {
      i++; const a = [];
      for (;;) {
        ws();
        if (raw[i] === "]") { i++; return a; }
        a.push(value()); ws();
        if (raw[i] === ",") { i++; continue; }
        if (raw[i] === "]") { i++; return a; }
        throw new Error("expected , or ] at " + i);
      }
    }
    if (c === '"' || c === "'") return str();
    const m = /^(?:[+-]?(?:Infinity|NaN|0x[0-9a-fA-F]+|(?:\\d+\\.?\\d*|\\.\\d+)(?:[eE][+-]?\\d+)?)|true|false|null)/.exec(raw.slice(i));
    if (!m) throw new Error("unexpected token at " + i);
    i += m[0].length;
    const t = m[0];
    if (t === "true") return true; if (t === "false") return false; if (t === "null") return null;
    return Number(t.replace(/^\\+/, ""));
  };
  try { const v = value(); ws(); return i >= n ? v : null; } catch { return null; }
}
function readJson(p) { try { return parseLoose(fs.readFileSync(p, "utf8")); } catch { return null; } }
function readEnvFile(p) {
  const out = {};
  try {
    for (const line of fs.readFileSync(p, "utf8").split(/\\r?\\n/)) {
      const m = line.match(/^\\s*(?:export\\s+)?([A-Z0-9_]+)\\s*=\\s*(.*?)\\s*$/i);
      if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  } catch {}
  return out;
}
/** Secret inputs may be a string, an env reference like \${NAME}, or { env: NAME } / { file: path }. */
function secretValue(v, env) {
  if (!v) return "";
  if (typeof v === "string") {
    const m = v.match(/^\\$\\{?([A-Z0-9_]+)\\}?$/i);
    return m ? env[m[1]] || "" : v;
  }
  if (typeof v === "object") {
    if (typeof v.value === "string") return v.value;
    if (typeof v.env === "string") return env[v.env] || "";
    if (typeof v.file === "string") { try { return fs.readFileSync(expand(v.file), "utf8").trim(); } catch { return ""; } }
    if (v.source === "env" && typeof v.id === "string") return env[v.id] || "";
  }
  return "";
}

/** What openclaw.json (plus env, auth profiles, IDENTITY.md) tells us about the bot. */
function readConfig(ws) {
  const notes = [];
  const sd = stateDir();
  const configPath = path.join(sd, "openclaw.json");
  const cfg = readJson(configPath) || {};
  if (!fs.existsSync(configPath)) notes.push("openclaw.json was not found at " + configPath + "; only the workspace files were imported.");
  else if (!Object.keys(cfg).length) notes.push("openclaw.json could not be parsed; only the workspace files were imported.");
  const env = { ...readEnvFile(path.join(sd, ".env")), ...readEnvFile(path.join(ws, ".env")), ...process.env };

  // Telegram token
  const tgRoots = [];
  const tg = cfg.channels && cfg.channels.telegram;
  if (tg) {
    tgRoots.push(tg);
    if (tg.accounts && typeof tg.accounts === "object") for (const a of Object.values(tg.accounts)) tgRoots.push(a);
  }
  let telegramBotToken = "";
  for (const r of tgRoots) {
    if (!r || typeof r !== "object") continue;
    telegramBotToken = secretValue(r.botToken, env);
    if (!telegramBotToken && typeof r.tokenFile === "string") { try { telegramBotToken = fs.readFileSync(expand(r.tokenFile), "utf8").trim(); } catch {} }
    if (telegramBotToken) break;
  }
  if (!telegramBotToken) telegramBotToken = env.TELEGRAM_BOT_TOKEN || "";

  // Model
  const defaults = (cfg.agents && cfg.agents.defaults) || {};
  const sel = defaults.model;
  const model = typeof sel === "string" ? sel : sel && typeof sel === "object" && typeof sel.primary === "string" ? sel.primary : "";

  // Name: identity in config, else IDENTITY.md ("name: X" / "**Name:** X" / first heading)
  let name = (defaults.identity && defaults.identity.name) || "";
  if (!name && cfg.agents && Array.isArray(cfg.agents.list)) for (const a of cfg.agents.list) if (a && a.identity && a.identity.name) { name = a.identity.name; break; }
  if (!name) {
    try {
      const id = fs.readFileSync(path.join(ws, "IDENTITY.md"), "utf8");
      const m = id.match(/^\\s*[-*]?\\s*\\**\\s*name\\s*\\**\\s*[:：]\\s*\\**\\s*([^\\n*]+)/im) || id.match(/^#\\s+(?!identity)([^\\n]+)/m);
      if (m) name = m[1].trim();
    } catch {}
  }

  // API keys: models.providers.*.apiKey, well-known env vars, legacy auth-profiles.json
  const keys = {};
  const providers = (cfg.models && cfg.models.providers) || {};
  for (const [id, p] of Object.entries(providers)) {
    if (!p || typeof p !== "object") continue;
    const apiKey = secretValue(p.apiKey, env);
    if (apiKey) keys[id] = { apiKey, baseUrl: typeof p.baseUrl === "string" ? p.baseUrl : undefined, source: "openclaw.json" };
  }
  const ENV_KEYS = { anthropic: "ANTHROPIC_API_KEY", openai: "OPENAI_API_KEY", openrouter: "OPENROUTER_API_KEY", google: ["GEMINI_API_KEY", "GOOGLE_API_KEY", "GOOGLE_GENERATIVE_AI_API_KEY"], deepseek: "DEEPSEEK_API_KEY", groq: "GROQ_API_KEY", mistral: "MISTRAL_API_KEY", xai: "XAI_API_KEY", together: "TOGETHER_API_KEY", fireworks: "FIREWORKS_API_KEY", cerebras: "CEREBRAS_API_KEY", deepinfra: "DEEPINFRA_API_KEY", moonshot: "MOONSHOT_API_KEY", zai: "ZAI_API_KEY", minimax: "MINIMAX_API_KEY", perplexity: "PERPLEXITY_API_KEY" };
  for (const [id, names] of Object.entries(ENV_KEYS)) {
    if (keys[id]) continue;
    for (const n of [].concat(names)) if (env[n]) { keys[id] = { apiKey: env[n], source: n }; break; }
  }
  const authFiles = [];
  try {
    const agentsRoot = path.join(sd, "agents");
    for (const e of fs.readdirSync(agentsRoot, { withFileTypes: true })) if (e.isDirectory()) authFiles.push(path.join(agentsRoot, e.name, "agent", "auth-profiles.json"));
  } catch {}
  authFiles.push(path.join(sd, "auth-profiles.json"), path.join(sd, "credentials", "auth-profiles.json"));
  for (const f of authFiles) {
    const j = readJson(f);
    const profiles = j && j.profiles;
    if (!profiles || typeof profiles !== "object") continue;
    for (const [pid, cred] of Object.entries(profiles)) {
      if (!cred || cred.type !== "api_key" || !cred.key) continue;
      const prov = cred.provider || pid.split(":")[0];
      if (prov && !keys[prov]) keys[prov] = { apiKey: cred.key, source: "auth-profiles" };
    }
  }
  return { telegramBotToken, model, name, keys, configPath, notes };
}

function looksLikeWorkspace(d) {
  return ["SOUL.md", "AGENTS.md", "MEMORY.md", "IDENTITY.md", "USER.md"].some((f) => fs.existsSync(path.join(d, f)));
}
function resolveWorkspace() {
  const cfg = readJson(path.join(stateDir(), "openclaw.json")) || {};
  const fromCfg = expand(cfg.agents && cfg.agents.defaults && cfg.agents.defaults.workspace) || expand(cfg.workspace);
  const cands = [expand(wsArg), fromCfg, path.join(stateDir(), "workspace"), process.cwd()].filter(Boolean);
  for (const d of cands) {
    try { if (fs.statSync(d).isDirectory() && (d === expand(wsArg) || looksLikeWorkspace(d))) return path.resolve(d); } catch {}
  }
  fail("could not find the OpenClaw workspace (looked in " + cands.join(", ") + "). Pass it explicitly: --workspace /path/to/workspace");
}
function walk(root) {
  const out = [];
  const rec = (dir, rel) => {
    let ents = [];
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of ents) {
      const r = rel ? rel + "/" + e.name : e.name;
      if (SKIP_DIRS.test(r) || e.isSymbolicLink()) continue;
      if (e.isDirectory()) rec(path.join(dir, e.name), r);
      else if (e.isFile()) {
        let size = 0;
        try { size = fs.statSync(path.join(dir, e.name)).size; } catch { continue; }
        out.push({ path: r, size });
        if (out.length >= MAX_FILES) return;
      }
    }
  };
  rec(root, "");
  return out;
}
async function api(p, init = {}) {
  const r = await fetch(API + "/api/import/s/" + token + p, { ...init, headers: { ...(init.headers || {}), "user-agent": "easylopster-import/2" } });
  let j = null;
  try { j = await r.json(); } catch {}
  if (!r.ok) throw new Error((j && j.error) || ("HTTP " + r.status));
  return j;
}
const fmt = (n) => (n >= 1048576 ? (n / 1048576).toFixed(1) + " MB" : n >= 1024 ? Math.round(n / 1024) + " KB" : n + " B");

(async () => {
  const ws = resolveWorkspace();
  log(c.bold + "easylopster import" + c.reset + c.dim + "  →  " + API + c.reset);
  log("workspace: " + ws);
  const config = readConfig(ws);
  // What the owner ticked on the page: keys / Telegram token stay on this machine when unchecked.
  let prefs = {};
  try { prefs = (await api("/options")) || {}; } catch (err) { fail(String(err.message || err)); }
  if (prefs.importKeys === false) { config.keys = {}; config.notes.push("API keys were kept on this machine (unchecked)."); }
  if (prefs.importTelegram === false) { config.telegramBotToken = ""; config.notes.push("The Telegram token was kept on this machine (unchecked)."); }
  const found = [config.telegramBotToken ? "Telegram token" : null, config.model ? "model " + config.model : null, Object.keys(config.keys).length ? Object.keys(config.keys).length + " API key(s): " + Object.keys(config.keys).join(", ") : null, config.name ? "name " + JSON.stringify(config.name) : null].filter(Boolean);
  log("config: " + (found.length ? found.join(" · ") : "nothing usable found in " + config.configPath));
  const files = walk(ws);
  log("found " + files.length + " files; sending the list…");
  let plan;
  try {
    plan = await api("/manifest", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ hostname: os.hostname(), workspace: ws, platform: process.platform, files, config }) });
  } catch (err) { fail(String(err.message || err)); }
  if (plan.created) {
    log(c.green + "created bot " + c.bold + plan.created.name + c.reset + c.green + (plan.created.tgUsername ? " (@" + plan.created.tgUsername + ")" : " (web chat only)") + (plan.created.model ? " · model " + plan.created.model : "") + c.reset);
    for (const k of plan.created.keys || []) log("  key: " + k);
    for (const n of plan.created.notes || []) log(c.dim + "  note: " + n + c.reset);
  }
  const upload = plan.upload || [];
  const bytes = upload.reduce((n, p) => n + (files.find((f) => f.path === p)?.size || 0), 0);
  log("bot: " + c.bold + plan.bot + c.reset + " · " + upload.length + " files to import (" + fmt(bytes) + "), " + plan.skipped + " skipped");
  if (!upload.length) {
    await api("/done", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }).catch(() => {});
    log(c.green + "nothing to upload; done." + c.reset);
    return;
  }
  const batches = [];
  let cur = [], curBytes = 0;
  for (const p of upload) {
    const size = files.find((f) => f.path === p)?.size || 0;
    if (cur.length >= plan.batchFiles || (curBytes + size > plan.batchBytes && cur.length)) { batches.push(cur); cur = []; curBytes = 0; }
    cur.push(p); curBytes += size;
  }
  if (cur.length) batches.push(cur);
  let done = 0, written = 0;
  for (let i = 0; i < batches.length; i++) {
    const fd = new FormData();
    fd.set("batch", JSON.stringify({ index: i, total: batches.length }));
    for (const p of batches[i]) {
      let buf;
      try { buf = fs.readFileSync(path.join(ws, p)); } catch { continue; }
      fd.append("file", new Blob([buf], { type: "text/plain" }), p);
    }
    let r;
    try { r = await api("/files", { method: "POST", body: fd }); }
    catch (err) {
      await api("/done", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ error: String(err.message || err) }) }).catch(() => {});
      fail("upload failed on batch " + (i + 1) + "/" + batches.length + ": " + (err.message || err));
    }
    done += batches[i].length;
    written += (r.written || []).length;
    const pct = Math.round((done / upload.length) * 100);
    process.stdout.write("\\r[" + "#".repeat(Math.round(pct / 4)).padEnd(25, "·") + "] " + pct + "%  " + done + "/" + upload.length + " files");
  }
  process.stdout.write("\\n");
  await api("/done", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" }).catch(() => {});
  log(c.green + "done: " + written + " files imported." + c.reset + " The Import page in your dashboard has the details.");
})().catch((err) => fail(String(err && err.message || err)));
`;
}

export function importSh(origin: string): string {
  return `#!/usr/bin/env bash
# easylopster — import an OpenClaw setup into your hosted account.
# Usage: curl -fsSL ${origin}/import.sh | bash -s -- TOKEN [--workspace DIR]
set -euo pipefail
if ! command -v node >/dev/null 2>&1; then
  echo "error: node was not found. OpenClaw needs Node 22+, so run this on the machine where OpenClaw is installed." >&2
  exit 1
fi
TMP="$(mktemp -d 2>/dev/null || mktemp -d -t easylopster)"
trap 'rm -rf "$TMP"' EXIT
curl -fsSL "${origin}/import.mjs" -o "$TMP/import.mjs"
node "$TMP/import.mjs" "$@"
`;
}

export function importPs1(origin: string): string {
  return `# easylopster — import an OpenClaw setup into your hosted account.
# Usage: $env:EASYLOPSTER_IMPORT_TOKEN="TOKEN"; irm ${origin}/import.ps1 | iex
$ErrorActionPreference = "Stop"
if (-not (Get-Command node -ErrorAction SilentlyContinue)) {
  Write-Host "error: node was not found. OpenClaw needs Node 22+, so run this on the machine where OpenClaw is installed." -ForegroundColor Red
  exit 1
}
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ("easylopster-import-" + [guid]::NewGuid().ToString("n") + ".mjs")
Invoke-WebRequest -UseBasicParsing "${origin}/import.mjs" -OutFile $tmp
try { node $tmp } finally { Remove-Item $tmp -ErrorAction SilentlyContinue }
`;
}

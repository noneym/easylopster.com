// Creates a migration by diffing the LIVE database against schema.prisma.
// Used instead of `prisma migrate dev` because the DB user cannot create a shadow database.
// Usage: pnpm migrate:new <name>   then   pnpm deploy
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import "dotenv/config";

const name = process.argv[2];
if (!name) {
  console.error("usage: pnpm migrate:new <name>");
  process.exit(1);
}
const url = process.env.DATABASE_URL;
if (!url) throw new Error("DATABASE_URL missing");
const stamp = new Date().toISOString().replace(/[-:TZ.]/g, "").slice(0, 14);
const dir = `prisma/migrations/${stamp}_${name}`;
const sql = execSync(
  `pnpm exec prisma migrate diff --from-config-datasource --to-schema prisma/schema.prisma --script`,
  { encoding: "utf8" },
);
if (!sql.trim() || /This is an empty migration/.test(sql)) {
  console.log("No schema changes detected.");
  process.exit(0);
}
mkdirSync(dir, { recursive: true });
writeFileSync(`${dir}/migration.sql`, sql);
if (!existsSync("prisma/migrations/migration_lock.toml")) {
  writeFileSync("prisma/migrations/migration_lock.toml", '# Please do not edit this file manually\nprovider = "mysql"\n');
}
console.log(`Wrote ${dir}/migration.sql`);
